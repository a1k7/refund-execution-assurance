"""Storage protocol. The verifier depends only on this interface, not on Database."""
from __future__ import annotations

from typing import Any, Dict, List, Optional, Protocol


class EvidenceLedgerReader(Protocol):
    def read_all(self) -> List[Dict[str, Any]]: ...
    def read_for_operation(self, business_operation_id: str) -> List[Dict[str, Any]]: ...
    def verify_chain(self) -> bool: ...
    def last_hash(self) -> Optional[str]: ...


class EvidenceLedgerWriter(Protocol):
    def append(self, event: Any) -> int: ...